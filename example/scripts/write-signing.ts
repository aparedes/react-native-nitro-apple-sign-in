const teamId = Bun.env.APPLE_TEAM_ID;
const bundleId = Bun.env.APPLE_BUNDLE_ID;

if (!teamId || !bundleId) {
  console.error(
    'Usage: env APPLE_TEAM_ID=<10-char team id> APPLE_BUNDLE_ID=<bundle id> bun run --cwd example signing',
  );
  process.exit(1);
}

if (!/^[A-Z0-9]{10}$/.test(teamId)) {
  console.error(`APPLE_TEAM_ID must match /^[A-Z0-9]{10}$/, got: ${teamId}`);
  process.exit(1);
}

const outPath = `${import.meta.dir}/../ios/Config/Signing.local.xcconfig`;

await Bun.write(
  outPath,
  `// Generated by \`bun run --cwd example signing\`. Gitignored.
DEVELOPMENT_TEAM = ${teamId}
PRODUCT_BUNDLE_IDENTIFIER = ${bundleId}
CODE_SIGN_STYLE = Automatic
`,
);

console.log(`Wrote ${outPath}`);
